import { test, expect } from "@playwright/test";
import { createHash, randomBytes, randomUUID } from "node:crypto";
import { readFileSync } from "node:fs";
import { Pool } from "pg";
import sharp from "sharp";
import { localStorageToken } from "./support/local-storage";

test("Next upload HTTP stores real images and preserves private ownership",async({request})=>{
 const owner=new Pool({host:"127.0.0.1",port:55432,database:"ourspace",user:"ourspace_owner",password:readFileSync(".local/db-password","utf8").trim(),max:1});
 const users=[randomUUID(),randomUUID()], sessions=users.map(()=>randomUUID()),tokens=users.map(()=>randomBytes(32).toString("base64url"));
 const headers=(i=0)=>({Origin:"http://127.0.0.1:3103",Cookie:`ourspace_session=${sessions[i]}:${tokens[i]}`});
 const storageHeaders={Authorization:`Bearer ${localStorageToken()}`,"Content-Type":"application/json"};
 const uploads:string[]=[]; const endpoint="/api/media/upload";
 try {
  await request.post("http://127.0.0.1:55435/bucket",{headers:storageHeaders,data:{id:"media",name:"media",public:false}});
  const bucket=await request.get("http://127.0.0.1:55435/bucket/media",{headers:storageHeaders});
  expect(bucket.status()).toBe(200); expect((await bucket.json()).public).toBe(false);
  for(let i=0;i<2;i++) {
   await owner.query("INSERT INTO m10.accounts(id,state) VALUES ($1,'active')",[users[i]]);
   await owner.query("INSERT INTO m10.sessions(id,account_id,token_hash,expires_at) VALUES ($1,$2,$3,now()+interval '1 hour')",[sessions[i],users[i],createHash("sha256").update(tokens[i]).digest("hex")]);
  }
  for(const format of ["png","jpeg","webp"] as const) {
   const bytes=await sharp({create:{width:12,height:10,channels:3,background:"blue"}}).toFormat(format).toBuffer();
   const intent={commandId:randomUUID(),title:"Synthetic "+format,mimeType:`image/${format}`,byteSize:bytes.length,sha256:createHash("sha256").update(bytes).digest("hex")};
   expect((await request.post(endpoint,{data:intent})).status()).toBe(403);
   expect((await request.post(endpoint,{headers:{Origin:headers().Origin},data:intent})).status()).toBe(401);
   const started=await request.post(endpoint,{headers:headers(),data:intent});expect(started.status()).toBe(200);
   const result=await started.json(); uploads.push(result.uploadId);
   expect(await (await request.post(endpoint,{headers:headers(),data:intent})).json()).toEqual(result);
   const path=endpoint+"?uploadId="+result.uploadId;
   const pending=await (await request.get(endpoint,{headers:headers()})).json();
   expect(pending.items).toContainEqual({uploadId:result.uploadId,title:intent.title,mimeType:intent.mimeType,byteSize:bytes.length,sha256:intent.sha256});
   expect(JSON.stringify(pending)).not.toContain("object_key");
   expect(await (await request.get(endpoint,{headers:headers(1)})).json()).toEqual({items:[],nextCursor:null});
   expect((await request.get(endpoint+"?after=bad",{headers:headers()})).status()).toBe(400);

   expect(await (await request.get(path,{headers:headers()})).json()).toMatchObject({state:"pending",mediaId:null});
   expect((await request.get(path,{headers:headers(1)})).status()).toBe(403);
   expect((await request.get(path+"&uploadId="+result.uploadId,{headers:headers()})).status()).toBe(400);
   const put=(data:Buffer,i=0)=>request.put(path,{headers:{...headers(i),"Content-Type":"application/octet-stream"},data});
   expect((await put(bytes,1)).status()).toBe(403);
   expect((await put(Buffer.alloc(100001))).status()).toBe(413);
   expect((await put(Buffer.from("invalid"))).status()).toBe(400);
   const responses=await Promise.all([put(bytes),put(bytes)]);
   expect(responses.map(r=>r.status())).toEqual([200,200]);
   const completed=await responses[0].json();expect(await responses[1].json()).toEqual(completed);
   const status=await request.get(path,{headers:headers()});expect(status.headers()["cache-control"]).toBe("no-store");
   expect(await status.json()).toEqual({uploadId:result.uploadId,mediaId:completed.mediaId,state:"completed"});
   const previewPath="/api/media/preview/"+completed.mediaId;
   const preview=await request.get(previewPath,{headers:headers()});expect(preview.status()).toBe(200);
   expect(preview.headers()["content-type"]).toBe("image/webp");expect(preview.headers()["cache-control"]).toContain("no-store");
   expect(preview.headers()["cross-origin-resource-policy"]).toBe("same-origin");
   const metadata=await sharp(await preview.body()).metadata();expect(metadata.format).toBe("webp");expect(metadata.width).toBeLessThanOrEqual(8);expect(metadata.height).toBeLessThanOrEqual(8);expect(metadata.exif).toBeUndefined();
   expect((await request.get(previewPath,{headers:headers(1)})).status()).toBe(404);
   expect((await request.get(previewPath)).status()).toBe(401);
   expect((await request.get(previewPath,{headers:{...headers(),Origin:"https://foreign.invalid"}})).status()).toBe(403);
   expect((await request.get(previewPath,{headers:{...headers(),Range:"bytes=0-1"}})).status()).toBe(416);
   expect((await request.get(previewPath+"?raw=true",{headers:headers()})).status()).toBe(400);
   const duplicatePath=path+"&duplicates=true";
   const candidates=await request.get(duplicatePath,{headers:headers()});
   expect(candidates.status()).toBe(200);expect(candidates.headers()["cache-control"]).toBe("no-store");
   expect(await candidates.json()).toEqual({items:[{mediaId:completed.mediaId,title:intent.title,mimeType:intent.mimeType}],nextCursor:null});
   expect((await request.get(duplicatePath,{headers:headers(1)})).status()).toBe(403);
   for(const suffix of ["&after=bad","&duplicates=true","&unknown=x"]) expect((await request.get(duplicatePath+suffix,{headers:headers()})).status()).toBe(400);
   expect(await (await request.get(duplicatePath+"&after="+completed.mediaId,{headers:headers()})).json()).toEqual({items:[],nextCursor:null});
   const foreign=await request.post(endpoint,{headers:headers(1),data:{...intent,commandId:randomUUID()}});
   expect(foreign.status()).toBe(200);const foreignId=(await foreign.json()).uploadId;uploads.push(foreignId);
   expect(await (await request.get(endpoint+"?uploadId="+foreignId+"&duplicates=true",{headers:headers(1)})).json()).toEqual({items:[],nextCursor:null});
   expect((await request.delete(endpoint+"?uploadId="+foreignId,{headers:headers(1)})).status()).toBe(200);
   const reuseStart=await request.post(endpoint,{headers:headers(),data:{...intent,commandId:randomUUID()}});
   expect(reuseStart.status()).toBe(200);const reuseId=(await reuseStart.json()).uploadId;uploads.push(reuseId);
   const reusePath=endpoint+"?uploadId="+reuseId;
   const choice={mediaId:completed.mediaId,confirmed:true};
   expect((await request.patch(reusePath,{headers:headers(),data:{...choice,confirmed:false}})).status()).toBe(400);
   expect((await request.patch(reusePath,{headers:headers(1),data:choice})).status()).toBe(403);
   expect((await request.patch(reusePath,{headers:{Cookie:headers().Cookie},data:choice})).status()).toBe(403);
   for(let i=0;i<2;i++){
    const reused=await request.patch(reusePath,{headers:headers(),data:choice});expect(reused.status()).toBe(200);
    expect(await reused.json()).toEqual({uploadId:reuseId,mediaId:completed.mediaId,state:"reused"});
   }
   expect(await (await request.get(reusePath,{headers:headers()})).json()).toEqual({uploadId:reuseId,mediaId:completed.mediaId,state:"reused"});
   expect((await request.put(reusePath,{headers:{...headers(),"Content-Type":"application/octet-stream"},data:bytes})).status()).toBe(409);
   const unused=(await owner.query("SELECT object_key FROM m02.upload_items WHERE id=$1",[reuseId])).rows[0];
   const missing=await request.get("http://127.0.0.1:55435/object/media/"+unused.object_key,{headers:storageHeaders});
   expect(missing.ok()).toBe(false);
   expect((await owner.query("SELECT count(*)::int AS n FROM m02.media WHERE uploaded_by=$1 AND mime_type=$2",[users[0],intent.mimeType])).rows[0].n).toBe(1);
   const separateStart=await request.post(endpoint,{headers:headers(),data:{...intent,commandId:randomUUID()}});
   expect(separateStart.status()).toBe(200);const separateId=(await separateStart.json()).uploadId;uploads.push(separateId);
   const separatePath=endpoint+"?uploadId="+separateId;
   const separateChoice={mode:"separate",confirmed:true};
   expect((await request.put(separatePath,{headers:{...headers(),"Content-Type":"application/octet-stream"},data:bytes})).status()).toBe(409);
   const blockedKey=(await owner.query("SELECT object_key FROM m02.upload_items WHERE id=$1",[separateId])).rows[0].object_key;
   expect((await request.get("http://127.0.0.1:55435/object/media/"+blockedKey,{headers:storageHeaders})).ok()).toBe(false);
   expect((await request.patch(separatePath,{headers:headers(1),data:separateChoice})).status()).toBe(403);
   expect((await request.patch(separatePath,{headers:headers(),data:{mode:"separate"}})).status()).toBe(400);
   for(let i=0;i<2;i++) expect(await (await request.patch(separatePath,{headers:headers(),data:separateChoice})).json()).toEqual({uploadId:separateId,mediaId:null,state:"pending",separate:true});
   expect((await request.patch(separatePath,{headers:headers(),data:choice})).status()).toBe(409);
   const separatePut=await request.put(separatePath,{headers:{...headers(),"Content-Type":"application/octet-stream"},data:bytes});
   expect(separatePut.status()).toBe(200);const separateMedia=(await separatePut.json()).mediaId;
   expect(separateMedia).not.toBe(completed.mediaId);
   expect(await (await request.get(separatePath,{headers:headers()})).json()).toEqual({uploadId:separateId,mediaId:separateMedia,state:"completed",separate:true});
   expect((await request.patch(separatePath,{headers:headers(),data:separateChoice})).status()).toBe(200);
   const separateKey=(await owner.query("SELECT object_key FROM app_internal.binary_objects WHERE resource_id=$1",[separateMedia])).rows[0].object_key;
   expect(await (await request.get("http://127.0.0.1:55435/object/media/"+separateKey,{headers:storageHeaders})).body()).toEqual(bytes);
   expect((await owner.query("SELECT count(*)::int AS n FROM m10.resource_grants WHERE resource_id=$1",[separateMedia])).rows[0].n).toBe(0);
   const binary=(await owner.query("SELECT object_key FROM app_internal.binary_objects WHERE resource_id=$1",[completed.mediaId])).rows[0];
   const stored=await request.get("http://127.0.0.1:55435/object/media/"+binary.object_key,{headers:storageHeaders});
   expect(await stored.body()).toEqual(bytes);
   expect((await (await request.get(endpoint,{headers:headers()})).json()).items).toEqual([]);

  }
  const gallery=await request.get("/api/media/list",{headers:headers()});expect(gallery.status()).toBe(200);
  expect(gallery.headers()["cache-control"]).toBe("no-store");
  const galleryData=await gallery.json();expect(galleryData.media).toHaveLength(6);expect(galleryData.nextCursor).toBeNull();
  expect(Object.keys(galleryData.media[0]).sort()).toEqual(["id","title","mimeType","createdAt","byteSize"].sort());
  expect(await (await request.get("/api/media/list",{headers:headers(1)})).json()).toEqual({media:[],nextCursor:null});
  for(const query of ["?after=bad","?after=","?after=a&after=b","?limit=100"]){expect((await request.get("/api/media/list"+query,{headers:headers()})).status()).toBe(400);}
  expect((await request.get("/api/media/list",{headers:{...headers(),Cookie:headers().Cookie+"; "+headers().Cookie}})).status()).toBe(401);
  const previewPath="/api/media/preview?mediaId="+galleryData.media[0].id;
  const preview=await request.get(previewPath,{headers:headers()});
  expect(preview.status()).toBe(200);
  expect(preview.headers()).toMatchObject({"cache-control":"no-store","content-type":"image/webp","cross-origin-resource-policy":"same-origin"});
  const thumbnail=await sharp(await preview.body()).metadata();
  expect(thumbnail).toMatchObject({format:"webp",width:8,height:7});
  expect(thumbnail.exif).toBeUndefined();
  const foreignPreview=await request.get(previewPath,{headers:headers(1)});
  const missingPreview=await request.get("/api/media/preview?mediaId="+randomUUID(),{headers:headers(1)});
  expect(foreignPreview.status()).toBe(404);expect(missingPreview.status()).toBe(404);
  expect(await foreignPreview.json()).toEqual(await missingPreview.json());
  expect((await request.get(previewPath,{headers:{...headers(),Origin:"https://else.example"}})).status()).toBe(403);
  expect((await request.get(previewPath)).status()).toBe(401);
  const additional=(await owner.query("SELECT app_internal.register_media($1,gen_random_uuid(),'Synthetic page','image/png','media',gen_random_uuid(),3,repeat('b',64)) AS id FROM generate_series(1,52)",[createHash("sha256").update(tokens[0]).digest("hex")])).rows.map(row=>row.id);
  const galleryFirst=await (await request.get("/api/media/list",{headers:headers()})).json();expect(galleryFirst.media).toHaveLength(50);
  const galleryLast=await (await request.get("/api/media/list?after="+galleryFirst.nextCursor,{headers:headers()})).json();expect(galleryLast.media).toHaveLength(8);expect(galleryLast.nextCursor).toBeNull();
  expect(new Set([...galleryFirst.media,...galleryLast.media].map((row:{id:string})=>row.id))).toEqual(new Set([...additional,...galleryData.media.map((row:{id:string})=>row.id)]));
  const cancelled=await request.post(endpoint,{headers:headers(),data:{commandId:randomUUID(),title:"Cancel synthetic",mimeType:"image/png",byteSize:3,sha256:"a".repeat(64)}});
  const cancelId=(await cancelled.json()).uploadId;uploads.push(cancelId);
  const cancelPath=endpoint+"?uploadId="+cancelId;
  expect((await request.delete(cancelPath,{headers:headers(1)})).status()).toBe(403);
  expect((await request.delete(cancelPath,{headers:{Cookie:headers().Cookie}})).status()).toBe(403);
  expect((await request.delete(cancelPath,{headers:headers(),data:{confirm:true}})).status()).toBe(400);
  for(let i=0;i<2;i++) expect((await request.delete(cancelPath,{headers:headers()})).status()).toBe(200);
  expect(await (await request.get(cancelPath,{headers:headers()})).json()).toEqual({uploadId:cancelId,mediaId:null,state:"cancelled"});
  expect((await request.put(cancelPath,{headers:{...headers(),"Content-Type":"application/octet-stream"},data:Buffer.from("bad")})).status()).toBe(403);
  expect((await request.delete(endpoint+"?uploadId="+uploads[0],{headers:headers()})).status()).toBe(409);
  expect((await (await request.get(endpoint,{headers:headers()})).json()).items).toEqual([]);
  const extra=(await owner.query("SELECT app_internal.begin_media_upload($1,gen_random_uuid(),'Synthetic page '||n,'image/png',3,repeat('a',64)) AS id FROM generate_series(1,52) n",[createHash("sha256").update(tokens[0]).digest("hex")])).rows.map(row=>row.id);
  uploads.push(...extra);
  const page1=await (await request.get(endpoint,{headers:headers()})).json();
  expect(page1.items).toHaveLength(50);expect(page1.nextCursor).toBeTruthy();
  const page2=await (await request.get(endpoint+"?after="+page1.nextCursor,{headers:headers()})).json();
  expect(page2.items).toHaveLength(2);expect(page2.nextCursor).toBeNull();
  expect(new Set([...page1.items,...page2.items].map((row:{uploadId:string})=>row.uploadId))).toEqual(new Set(extra));
  await owner.query("UPDATE m10.sessions SET revoked_at=clock_timestamp() WHERE id=$1",[sessions[0]]);
  expect((await request.get(endpoint+"?uploadId="+uploads[0],{headers:headers()})).status()).toBe(401);
  expect((await request.get(endpoint+"?uploadId="+uploads[0]+"&duplicates=true",{headers:headers()})).status()).toBe(401);
  expect((await request.get(endpoint,{headers:headers()})).status()).toBe(401);
  expect((await request.get("/api/media/list",{headers:headers()})).status()).toBe(401);
  expect((await request.get("/api/media/preview/"+galleryData.media[0].id,{headers:headers()})).status()).toBe(401);
  expect((await request.get(previewPath,{headers:headers()})).status()).toBe(401);
 } finally {
  const keys=(await owner.query("SELECT object_key FROM m02.upload_items WHERE id=ANY($1::uuid[])",[uploads])).rows.map(r=>r.object_key);
  if(keys.length) expect((await request.delete("http://127.0.0.1:55435/object/media",{headers:storageHeaders,data:{prefixes:keys}})).status()).toBe(200);
  await owner.query("UPDATE m10.sessions SET revoked_at=clock_timestamp() WHERE account_id=ANY($1::uuid[]) AND revoked_at IS NULL",[users]);
  await owner.end();
 }
});
